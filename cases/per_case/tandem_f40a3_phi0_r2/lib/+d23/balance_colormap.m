function cmap = balance_colormap(n)
%BALANCE_COLORMAP Interpolated cmocean balance map with an exact white zero.
if nargin < 1 || isempty(n)
    n = 257;
end
if ~isscalar(n) || ~isfinite(n) || n < 3 || n ~= fix(n)
    error('d23:balance_colormap:InvalidSize', ...
        'Colormap size must be a finite integer of at least three.');
end

base = [ ...
    0.0931763018011579 0.1111733294776027 0.2615123885530548
    0.1420239025529175 0.1821139210721199 0.4288312063871852
    0.1605144853740181 0.2520449664884137 0.6176326884994885
    0.0599723938852101 0.3518724589197287 0.7451112677451700
    0.1137086176106715 0.4600994415937408 0.7332669709261729
    0.2531842141782504 0.5532868030196056 0.7283682664224710
    0.4021568777342401 0.6385726062767525 0.7368283596175828
    0.5692137827295344 0.7158374507334064 0.7658846391640979
    0.7286379384465542 0.7947311600603628 0.8189949911619621
    0.8784382335627493 0.8821357286003169 0.8877941282875983
    0.9193158312207209 0.8688709544014415 0.8556984957170943
    0.8765819558343688 0.7453617807828379 0.7041425081848088
    0.8398121280126148 0.6245924501696032 0.5518333419186968
    0.8034606454253448 0.5044996405205642 0.4032462569229745
    0.7636320165602665 0.3813243782834011 0.2652462569229745
    0.7149309099320342 0.2481683165272228 0.1607679806208324
    0.6353308455824535 0.1163746016461593 0.1462643713521036
    0.5116825300936565 0.0551506371953276 0.1620362461608068
    0.3712442490169728 0.0559369332496281 0.1311404343886696
    0.2360563646646140 0.0352974799460403 0.0694374423941256];
base_position = linspace(0, 1, size(base, 1)).';
base_position = [base_position(1:10); 0.5; base_position(11:end)];
base = [base(1:10,:); 1 1 1; base(11:end,:)];
cmap = interp1(base_position, base, linspace(0, 1, n), 'linear');
cmap = min(max(cmap, 0), 1);
if mod(n, 2) == 1
    cmap((n + 1) / 2, :) = [1 1 1];
end
end
